
-- =====================================================
-- PEMANTAUAN KETERJADIAN RISIKO PER TRIWULAN
-- =====================================================

CREATE TABLE IF NOT EXISTS public.pemantauan_keterjadian_risiko (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

    id_identifikasi INTEGER NOT NULL,

    tahun INTEGER NOT NULL,

    triwulan SMALLINT NOT NULL
        CHECK (triwulan BETWEEN 1 AND 4),

    keterjadian_risiko VARCHAR(2) NOT NULL DEFAULT 'TT'
        CHECK (keterjadian_risiko IN ('T', 'TT', 'BT')),

    jumlah_keterjadian INTEGER NOT NULL DEFAULT 0
        CHECK (jumlah_keterjadian >= 0),

    created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT fk_pemantauan_keterjadian_identifikasi
        FOREIGN KEY (id_identifikasi)
        REFERENCES public.identifikasi_risiko(id_identifikasi)
        ON DELETE CASCADE,

    CONSTRAINT uq_pemantauan_keterjadian_per_periode
        UNIQUE (id_identifikasi, tahun, triwulan),

    CONSTRAINT chk_jumlah_keterjadian
        CHECK (keterjadian_risiko = 'T' OR jumlah_keterjadian = 0)
);

-- Index untuk mempercepat pencarian berdasarkan tahun dan triwulan
CREATE INDEX IF NOT EXISTS idx_pemantauan_keterjadian_periode
ON public.pemantauan_keterjadian_risiko (tahun, triwulan);
